def describe(filename, col):
    """Return (description, found)."""
    ov = OVERRIDES.get(filename, {})
    if col in ov:
        return ov[col], True
    if col in COLUMNS:
        return COLUMNS[col], True
    for rx, text in PATTERNS:
        m = rx.match(col)
        if m:
            return text.format(*m.groups()), True
    return "", False
